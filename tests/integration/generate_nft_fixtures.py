"""Create nonsensitive, local test policy fixtures for rootless WireGuard lab.

Executed ONLY inside the disposable private mount/network namespace. The
WireGuard public keys used here are the keys generated by that same lab.
"""
from __future__ import annotations

from pathlib import Path
import base64
import binascii
import hmac
import json
import os
import stat
import sys

from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
from goreecloud_vpn.core import VPNStore
from goreecloud_vpn.enrollment import ProofChallenges, device_proof
from goreecloud_vpn.firewall_preview import build_nft_ingress_preview
from goreecloud_vpn.identity_binding import build_key_address_binding_intent

# Import in both direct-shell execution and unittest namespace-import modes.
if __package__:
    from .port_probe import _assert_isolated_lab
else:
    from port_probe import _assert_isolated_lab


def _lab_private_key(path: Path, expected_public: str) -> X25519PrivateKey:
    """Read a *disposable* wg genkey file from private tmpfs, never a host key.

    Refuse aliases, insecure mode, unexpected size and mismatched public keys.
    Do not print key bytes, input path, or underlying exception details.
    """
    if not hasattr(os, "O_NOFOLLOW"):
        raise RuntimeError("safe private lab key open unavailable")
    try:
        fd = os.open(
            path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK
            | getattr(os, "O_CLOEXEC", 0),
        )
    except OSError:
        raise RuntimeError("lab-only private key unavailable") from None
    try:
        before = os.fstat(fd)
        if (not stat.S_ISREG(before.st_mode) or before.st_uid != os.geteuid()
                or before.st_nlink != 1 or before.st_mode & 0o077
                or not 44 <= before.st_size <= 128):
            raise RuntimeError("unsafe lab-only key properties")
        raw = os.read(fd, 129)
        after = os.fstat(fd)
        if (len(raw) != before.st_size or before.st_size != after.st_size
                or before.st_mtime_ns != after.st_mtime_ns
                or before.st_ctime_ns != after.st_ctime_ns):
            raise RuntimeError("lab-only key changed during read")
    finally:
        os.close(fd)
    try:
        secret = base64.b64decode(raw.strip(), validate=True)
        if len(secret) != 32:
            raise RuntimeError("invalid lab-only private key size")
        private = X25519PrivateKey.from_private_bytes(secret)
        public = base64.b64encode(private.public_key().public_bytes(
            Encoding.Raw, PublicFormat.Raw,
        )).decode("ascii")
        if not hmac.compare_digest(public, expected_public):
            raise RuntimeError("lab-only public and private keys disagree")
        return private
    except (ValueError, binascii.Error):
        raise RuntimeError("invalid lab-only private key") from None


def generate(directory: Path) -> None:
    # This helper now reads ephemeral private test keys. Enforce the same
    # rootless network/mount namespace proof as every active lab probe.
    _assert_isolated_lab()
    if directory.is_symlink():
        raise ValueError("fixture directory cannot be a symlink")
    directory = directory.resolve(strict=True)
    if not directory.is_dir():
        raise ValueError("fixture target must be a directory")
    if directory.stat().st_uid != os.geteuid() or directory.stat().st_mode & 0o077:
        raise ValueError("fixture directory must be private to this process")
    a = directory / "a.pub"
    b = directory / "b.pub"
    if a.is_symlink() or b.is_symlink():
        raise ValueError("public key paths cannot be symlinks")
    source_key = a.read_text(encoding="ascii").strip()
    target_key = b.read_text(encoding="ascii").strip()
    # The only source for these test private keys is the throwaway lab
    # tmpfs generated by wg genkey. Never load a real client or host key.
    source_private = _lab_private_key(directory / "a.priv", source_key)
    target_private = _lab_private_key(directory / "b.priv", target_key)
    store_path = directory / "fixture.db"
    if store_path.exists():
        raise ValueError("fixture database already exists")

    store = VPNStore(store_path, subnet="10.77.0.0/24")
    try:
        source = store.add_peer("labsource", source_key, ["users"])
        target = store.add_peer("labtarget", target_key, ["services"])
        if source["address"] != "10.77.0.10" or target["address"] != "10.77.0.11":
            raise RuntimeError("unexpected lab address allocation")
        # PR #6 requires real key possession. Do not bypass the gate through
        # direct record_device_proof or a test-only administrative override.
        proofs = ProofChallenges(store)
        for peer, private in ((source, source_private), (target, target_private)):
            if store.approve_peer(peer["id"]):
                raise RuntimeError("unproved lab peer was unexpectedly approved")
            challenge = proofs.issue(peer["id"])
            if not proofs.verify(
                peer["id"], challenge["challenge_id"],
                device_proof(private, challenge),
            ):
                raise RuntimeError("lab-only X25519 key possession failed")
            if not store.approve_peer(peer["id"]):
                raise RuntimeError("cannot approve proved lab-only peer")
        # Public-only binding intent, built from the same disposable approved
        # peer records used to compile the nftables policy fixtures.
        intent = build_key_address_binding_intent(store)
        for filename, data in (
            ("binding-intent.json", json.dumps(intent, sort_keys=True)),
            ("binding-source-id.txt", source["id"]),
        ):
            destination = directory / filename
            with destination.open("x", encoding="ascii") as output:
                output.write(data)
            destination.chmod(0o600)

        outputs = {
            "deny.nft": build_nft_ingress_preview(store, target["id"], interface="wgB"),
        }
        icmp = store.add_policy("users", "services", "icmp", [])
        outputs["allow.nft"] = build_nft_ingress_preview(
            store, target["id"], interface="wgB"
        )
        if not store.delete_policy(icmp["id"]):
            raise RuntimeError("cannot remove temporary ICMP lab rule")
        store.add_policy("users", "services", "tcp", [8443])
        store.add_policy("users", "services", "udp", [5353])
        outputs["ports.nft"] = build_nft_ingress_preview(
            store, target["id"], interface="wgB"
        )
        # No services -> users policy exists. The other endpoint must not
        # treat handshake/AllowedIPs alone as reverse-direction authorization.
        outputs["reverse.deny.nft"] = build_nft_ingress_preview(
            store, source["id"], interface="wgA"
        )
        # Freeze the same public-only lab generation used by ports.nft.
        # These temporary records never leave this private tmpfs.
        lab_peers, lab_policies = store.snapshot()
        lab_snapshot = {
            "pool": str(store.network), "target_peer_id": target["id"],
            "peers": lab_peers, "policies": lab_policies,
        }
        snapshot_file = directory / "lab-state.json"
        with snapshot_file.open("x", encoding="ascii") as out:
            json.dump(lab_snapshot, out, sort_keys=True)
        snapshot_file.chmod(0o600)

        for name, plan in outputs.items():
            path = directory / name
            with path.open("x", encoding="ascii") as out:
                out.write(plan["nftables_text"])
            path.chmod(0o600)
            update_path = directory / name.replace(".nft", ".replace.nft")
            with update_path.open("x", encoding="ascii") as out:
                out.write(plan["nftables_replace_transaction_text"])
            update_path.chmod(0o600)
        if outputs["deny.nft"]["allow_rule_count"] != 0:
            raise RuntimeError("expected no allow entries in deny fixture")
        if outputs["allow.nft"]["allow_rule_count"] != 1:
            raise RuntimeError("expected exactly one ICMP allow entry")
        if outputs["ports.nft"]["allow_rule_count"] != 2:
            raise RuntimeError("expected exactly two TCP/UDP allow entries")
        if outputs["reverse.deny.nft"]["allow_rule_count"] != 0:
            raise RuntimeError("expected no reverse-direction allow entries")
    finally:
        store.close()
        store_path.unlink(missing_ok=True)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python generate_nft_fixtures.py PRIVATE_TMPFS_DIRECTORY")
    generate(Path(sys.argv[1]))
